package WeBWorK::CourseConfig;
use Mojo::Base 'Exporter', -signatures;

=head1 NAME

WeBWorK::CourseConfig - Utilities for saving a course's web based configuration
in the course's F<simple.conf> file.

=cut

use Mojo::File qw(path);

use WeBWorK::CourseEnvironment;
use WeBWorK::ConfigObject::text;
use WeBWorK::ConfigObject::timezone;
use WeBWorK::ConfigObject::time;
use WeBWorK::ConfigObject::number;
use WeBWorK::ConfigObject::boolean;
use WeBWorK::ConfigObject::permission;
use WeBWorK::ConfigObject::permission_checkboxlist;
use WeBWorK::ConfigObject::list;
use WeBWorK::ConfigObject::checkboxlist;
use WeBWorK::ConfigObject::popuplist;
use WeBWorK::ConfigObject::setting;
use WeBWorK::ConfigObject::lms_context_id;
use WeBWorK::ConfigValues qw(getConfigValues);

our @EXPORT_OK = qw(configObject findConfigObject canChangeConfig buildSimpleConfig writeSimpleConfig);

=head1 FUNCTIONS

=head2 configObject

    my $configObject = configObject($c, $data, %options);

Create a C<WeBWorK::ConfigObject> of the type given in the C<$data> hash (an
entry from C<getConfigValues>).  If the C<input_name> option is given, then the
new value for the setting is taken from that request parameter instead of the
parameter that the configuration page form uses.

=cut

sub configObject ($c, $data, %options) {
	return "WeBWorK::ConfigObject::$data->{type}"->new({ %$data, %options }, $c);
}

=head2 findConfigObject

    my $configObject = findConfigObject($c, $var, %options);

Find the configuration value whose variable name is C<$var>, and return a
C<WeBWorK::ConfigObject> for it.  Returns undefined if C<$var> is not a
configurable variable.

=cut

sub findConfigObject ($c, $var, %options) {
	for my $configSection (@{ getConfigValues($c->ce) }) {
		for my $data (@$configSection[ 1 .. $#$configSection ]) {
			return configObject($c, $data, %options) if $data->{var} eq $var;
		}
	}
	return;
}

=head2 canChangeConfig

    my $allowed = canChangeConfig($c, $var);

Returns true if the current user is allowed to change the configuration variable
C<$var>.

=cut

sub canChangeConfig ($c, $var) {
	return !defined $c->ce->{permissionLevels}{"change_config_$var"}
		|| $c->authz->hasPermissions($c->authen->{user_id}, "change_config_$var");
}

=head2 buildSimpleConfig

    my ($contents, $errors) = buildSimpleConfig($c, %options);

Build the contents of the course's F<simple.conf> file.  All configuration
values that differ from the default value (the value without F<simple.conf>
loaded) are saved.  New values are taken from the request parameters, except for
variables the user does not have permission to change, for which the current
course environment value is kept.

If the C<var> option is given, then only that variable is changed and all other
variables keep their current course environment values.  The C<input_name>
option is passed on to C<configObject>.

Invalid submitted values are not saved and the current course environment value
is kept instead.  A reference to an array of messages describing those invalid
values is returned along with the file contents.

Note that values of the C<setting> and C<lms_context_id> types are saved to the
database by this method.

=cut

sub buildSimpleConfig ($c, %options) {
	my $ce = $c->ce;

	# Get a copy of the course environment which does not have simple.conf loaded.
	my $defaultCE = WeBWorK::CourseEnvironment->new({
		courseName          => $ce->{courseName},
		web_config_filename => 'noSuchFilePlease'
	});

	my $contents = <<~'END_SIMPLE_CONF_HEADER';
		#!perl
		# This file is automatically generated by WeBWorK's web-based
		# configuration module.  Do not make changes directly to this
		# file.  It will be overwritten the next time configuration
		# changes are saved.

		END_SIMPLE_CONF_HEADER

	my @errors;

	for my $configSection (@{ getConfigValues($ce) }) {
		for my $data (@$configSection[ 1 .. $#$configSection ]) {
			my $configObject = configObject($c, $data, input_name => $options{input_name});
			my $useCurrent   = (defined $options{var} && $options{var} ne $data->{var})
				|| !canChangeConfig($c, $data->{var});
			$contents .= $configObject->save_string($configObject->get_value($defaultCE), $useCurrent);
			push(@errors, $configObject->errors);
		}
	}

	return ($contents, \@errors);
}

=head2 writeSimpleConfig

    my $success = writeSimpleConfig($ce, $contents);

Write C<$contents> to the course's F<simple.conf> file.  Returns true on
success.

=cut

sub writeSimpleConfig ($ce, $contents) {
	eval { path($ce->{courseDirs}{root}, 'simple.conf')->spew($contents, 'UTF-8') };
	return $@ ? 0 : 1;
}

1;
